"use strict";
// Real Chromium complements the deterministic VM tests: native shader
// compilation/linking, rasterized pixels and real DOM event dispatch.
const assert = require("node:assert/strict");
const path = require("node:path");
const { pathToFileURL } = require("node:url");
const { chromium } = require("playwright");

if (process.argv.length !== 3) {
  throw new Error("usage: test-report-browser.js DIR — reports generated by just report-browser");
}

// Runs before the report, forwarding every call to the native implementation.
// Read WebGL pixels within the draw: its default drawing buffer need not
// survive presentation. No shader status, context or drawing call is stubbed.
function observeRendering() {
  const state = { shaders: [], programs: [], draws: 0, glErrors: [], pixels: null, canvases: {} };
  window.__animsmithBrowserSmoke = state;
  function summarize(bytes, width, height) {
    let changed = 0;
    for (let i = 4; i < bytes.length; i += 4) {
      if (bytes[i] !== bytes[0] || bytes[i + 1] !== bytes[1] ||
          bytes[i + 2] !== bytes[2] || bytes[i + 3] !== bytes[3]) changed++;
    }
    return { width, height, changed };
  }
  function checkSize(width, height) {
    // These fixed synthetic fixtures use a 1100x800, DPR=1 viewport.
    // A broken layout must not turn smoke readback into an unbounded allocation.
    if (width < 1 || height < 1 || width * height > 1_000_000) {
      throw new Error(`unexpected smoke framebuffer size ${width}x${height}`);
    }
  }
  const gl = WebGL2RenderingContext.prototype;
  const compile = gl.compileShader;
  gl.compileShader = function (shader) {
    const result = compile.call(this, shader);
    state.shaders.push({ ok: this.getShaderParameter(shader, this.COMPILE_STATUS), log: this.getShaderInfoLog(shader) });
    return result;
  };
  const link = gl.linkProgram;
  gl.linkProgram = function (program) {
    const result = link.call(this, program);
    state.programs.push({ ok: this.getProgramParameter(program, this.LINK_STATUS), log: this.getProgramInfoLog(program) });
    return result;
  };
  for (const method of ["drawArrays", "drawElements"]) {
    const draw = gl[method];
    gl[method] = function (...args) {
      const result = draw.apply(this, args);
      state.draws++;
      if (!state.pixels?.changed) {
        const width = this.drawingBufferWidth, height = this.drawingBufferHeight;
        checkSize(width, height);
        const bytes = new Uint8Array(width * height * 4);
        this.readPixels(0, 0, width, height, this.RGBA, this.UNSIGNED_BYTE, bytes);
        state.pixels = summarize(bytes, width, height);
      }
      const error = this.getError();
      if (error !== this.NO_ERROR) state.glErrors.push(error);
      return result;
    };
  }
  for (const method of ["stroke", "fill"]) {
    const draw = CanvasRenderingContext2D.prototype[method];
    CanvasRenderingContext2D.prototype[method] = function (...args) {
      const result = draw.apply(this, args);
      const canvas = this.canvas;
      const record = state.canvases[canvas.id] ||= { draws: 0, pixels: null };
      record.draws++;
      if (!record.pixels?.changed) {
        checkSize(canvas.width, canvas.height);
        record.pixels = summarize(this.getImageData(0, 0, canvas.width, canvas.height).data, canvas.width, canvas.height);
      }
      return result;
    };
  }
}

async function checkReport(context, name, mode) {
  const page = await context.newPage();
  const errors = [], requests = [];
  page.on("pageerror", error => errors.push(`page: ${error.message}`));
  page.on("console", message => { if (message.type() === "error") errors.push(`console: ${message.text()}`); });
  page.on("request", request => {
    if (!/^(file|data|blob):/.test(request.url())) requests.push(request.url());
  });
  await page.addInitScript(observeRendering);
  try {
    await page.goto(pathToFileURL(path.resolve(process.argv[2], `${name}.html`)).href, { waitUntil: "load", timeout: 10_000 });
    await page.waitForFunction(mode => {
      const state = window.__animsmithBrowserSmoke;
      if (mode === "webgl") {
        return state.shaders.some(shader => !shader.ok) || state.programs.some(program => !program.ok) || state.pixels?.changed > 0;
      }
      if (mode === "canvas2d") return ["before-gl", "after-gl"].every(id => state.canvases[id]?.pixels?.changed > 0);
      return document.getElementById("file")?.textContent.trim() || document.getElementById("mapping")?.textContent.trim();
    }, mode, { timeout: 10_000 });

    if (mode === "webgl") {
      const state = await page.evaluate(() => window.__animsmithBrowserSmoke);
      assert(state.shaders.length > 0 && state.shaders.every(shader => shader.ok), `shader compilation: ${JSON.stringify(state.shaders)}`);
      assert(state.programs.length > 0 && state.programs.every(program => program.ok), `program linking: ${JSON.stringify(state.programs)}`);
    }
    if (mode.startsWith("evidence")) {
      assert.equal(await page.locator("canvas").count(), 0, "evidence-only report must omit pose canvases");
      assert(await page.locator("#play").isDisabled(), "evidence-only playback must be disabled");
      if (mode === "evidence-comparison") {
        assert(await page.locator("#scrub").isDisabled(), "comparison evidence has no shared pose phase to scrub");
      } else {
        // Ordinary evidence keeps its chart playhead, even without pose data.
        const time = await page.locator("#time").textContent();
        assert(!await page.locator("#scrub").isDisabled(), "ordinary evidence keeps chart scrubbing");
        await page.locator("#scrub").focus();
        await page.keyboard.press("ArrowRight");
        await page.waitForFunction(previous => document.getElementById("time").textContent !== previous, time, { timeout: 10_000 });
      }
    } else {
      const draws = await page.evaluate(() => {
        const state = window.__animsmithBrowserSmoke;
        return state.draws + Object.values(state.canvases).reduce((sum, canvas) => sum + canvas.draws, 0);
      });
      // Exercise an actual browser input event and its report listener.
      await page.locator("#scrub").focus();
      await page.keyboard.press("ArrowRight");
      await page.waitForFunction(previous => {
        const state = window.__animsmithBrowserSmoke;
        const draws = state.draws + Object.values(state.canvases).reduce((sum, canvas) => sum + canvas.draws, 0);
        return Number(document.getElementById("scrub").value) > 0 && draws > previous;
      }, draws, { timeout: 10_000 });
    }

    const state = await page.evaluate(() => window.__animsmithBrowserSmoke);
    assert.deepEqual(errors, [], "browser errors");
    assert.deepEqual(requests, [], "self-contained reports must not request the network");
    assert.deepEqual(state.glErrors, [], "native WebGL errors");
    if (mode === "webgl") {
      assert(state.draws > 0 && state.pixels?.changed > 0, "WebGL frame must contain nonuniform pixels");
    }
    if (mode === "canvas2d") {
      for (const id of ["before-gl", "after-gl"]) {
        assert(state.canvases[id]?.pixels?.changed > 0, `${id} must contain rendered pixels`);
      }
    }
    console.log(`${name}: ${JSON.stringify(state)}`);
  } catch (error) {
    const state = await page.evaluate(() => window.__animsmithBrowserSmoke).catch(() => null);
    throw new Error(`${name}: ${error.message}\n${JSON.stringify({ errors, requests, state })}`, { cause: error });
  } finally {
    await page.close();
  }
}

async function main() {
  // Explicit software rasterization makes this a reproducible Chromium smoke,
  // not a claim about hardware GPUs, other browsers or engine rendering.
  const browser = await chromium.launch({
    headless: true,
    timeout: 30_000,
    args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"],
  });
  try {
    console.log(`Chromium ${browser.version()} with SwiftShader`);
    const context = await browser.newContext({ viewport: { width: 1100, height: 800 }, deviceScaleFactor: 1, offline: true, serviceWorkers: "block" });
    await context.route("**/*", route => /^(file|data|blob):/.test(route.request().url()) ? route.continue() : route.abort());
    for (const [name, mode] of [
      ["report", "webgl"], ["comparison", "canvas2d"],
      ["report-evidence", "evidence-single"], ["comparison-evidence", "evidence-comparison"],
    ]) await checkReport(context, name, mode);
  } finally {
    await browser.close();
  }
}

main().catch(error => { console.error(error); process.exitCode = 1; });
